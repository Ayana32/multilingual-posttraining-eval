"""Independent, hand-specified loss-mask check: on a short crafted example, the
user text and the tool-result content MUST be masked (-100) and the gold
record_expense call MUST be in the labels. The expectations are written by hand
(distinctive sentinel strings) and checked against assistant_token_labels'
output -- not regenerated by it. Needs the tokenizer -> `network`."""
from __future__ import annotations
import json
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "phase4"))
import checks  # noqa: E402  (assistant_token_labels)

REV = "ebb281ec70b05090aa6165b016eac8ec08e71b17"

USER_SENTINEL = "ZZUSERTEXT77"
TOOL_SENTINEL = "ZZTOOLRESULT88"
VENDOR = "Qwilping Cafe"
REPLY_SENTINEL = "ZZFINALREPLY99"

MESSAGES = [
    {"role": "system", "content": "You are an assistant that processes receipts."},
    {"role": "user", "content": f"{USER_SENTINEL} Record this receipt as an expense.\n{VENDOR}\n01 Jan 2025\nTotal: 5.00 GBP\n"},
    {"role": "assistant", "content": "",
     "tool_calls": [{"type": "function", "function": {"name": "record_expense",
                     "arguments": {"vendor": VENDOR, "date": "01 Jan 2025", "amount": "5.00", "currency": "GBP"}}}]},
    {"role": "tool", "content": json.dumps({"status": TOOL_SENTINEL})},
    {"role": "assistant", "content": REPLY_SENTINEL},
]


@pytest.mark.network
def test_loss_mask_handwritten_expectations():
    from transformers import AutoTokenizer
    tok = AutoTokenizer.from_pretrained("Qwen/Qwen3-VL-4B-Instruct", revision=REV)
    tools = json.loads((REPO / "phase3" / "fixtures" / "tools.json").read_text())

    ids, labels, spans = checks.assistant_token_labels(MESSAGES, tok, tools)
    assert len(ids) == len(labels)
    loss = tok.decode([t for t, l in zip(ids, labels) if l != -100])
    masked = tok.decode([t for t, l in zip(ids, labels) if l == -100])

    # user text -> masked, never in loss
    assert USER_SENTINEL in masked and USER_SENTINEL not in loss
    # tool result -> masked, never in loss
    assert TOOL_SENTINEL in masked and TOOL_SENTINEL not in loss
    # gold record_expense call (name + every argument value) -> in the labels
    assert "record_expense" in loss
    for v in (VENDOR, "01 Jan 2025", "5.00", "GBP"):
        assert v in loss, f"gold arg {v!r} must be in the loss region"
    # the final reply (an assistant token) -> in the labels
    assert REPLY_SENTINEL in loss
    # exactly two assistant spans (tool-call turn + final reply)
    assert len(spans) == 2
